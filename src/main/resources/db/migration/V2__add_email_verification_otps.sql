-- OTP xác nhận email khi đăng ký (6 chữ số, hiệu lực 10 phút, tối đa 5 lần thử)
-- Dùng cú pháp ANSI (tương thích H2 test + PostgreSQL prod)
CREATE TABLE email_verification_otps (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(180)  NOT NULL,
    otp_hash      VARCHAR(64)   NOT NULL,
    full_name     VARCHAR(150)  NOT NULL,
    phone         VARCHAR(20),
    password_hash VARCHAR(255)  NOT NULL,
    attempts      INT           NOT NULL DEFAULT 0,
    expires_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    verified_at   TIMESTAMP WITH TIME ZONE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_email_verification_otps_email ON email_verification_otps(email);
